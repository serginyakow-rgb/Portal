"""Синхронизация разделов портала между сотрудниками: версия и фрагмент.

Раздел, который должен обновляться у всех открытых экранов сам (первым стал
раздел «Задачи»), отдаёт два адреса:

* ``GET <раздел>/state`` — JSON-состояние: как минимум ``{"version": "…"}``.
  Схему ответа раздел описывает наследником :class:`SectionState` и добавляет
  в неё то, что нужно обновлять вместе с разметкой;
* ``GET <раздел>/fragment`` — та же разметка, что показывает страница, но
  фрагментом (``render_partial``, без шапки и меню) и с заголовком
  ``X-Section-Version`` — версией ровно этого фрагмента.

Клиент (``app/static/js/sync.js``) раз в несколько секунд спрашивает состояние,
сравнивает версию с той, что показывает, и при расхождении забирает фрагмент
и подменяет им разметку. Версию считает :func:`revision` по данным раздела:
изменилась любая часть отпечатка — изменилась версия.

Порядок подключения нового раздела — в ``PROJECT_MAP.md`` (§8.7).
"""
import hashlib

from fastapi import Response
from pydantic import BaseModel

# Заголовок ответа с версией фрагмента. То же имя задано в app/static/js/sync.js:
# раздел и скрипт должны сходиться, иначе подмена пойдёт на каждый опрос
VERSION_HEADER = "X-Section-Version"

# Сколько символов отпечатка оставляем в версии: 12 hex-символов хватает, чтобы
# различить состояния, и коротко для заголовка, JSON и data-атрибута шаблона
VERSION_LENGTH = 12


class SectionState(BaseModel):
    """Ответ «состояние раздела»: версия и поля конкретного раздела.

    Базовый контракт со скриптом — одно поле ``version``: его сравнивает
    ``js/sync.js``. Наследник добавляет всё, что раздел обновляет вместе
    с разметкой (у «Задач» — числа метки в меню и окна по сотрудникам).
    """

    version: str


def revision(*parts: object) -> str:
    """Отпечаток состояния раздела для сверки «изменилось ли что-нибудь».

    Части — любые значения, влияющие на разметку раздела: числа, даты, имена.
    Они приводятся к строке и склеиваются через «|», поэтому порядок частей
    задаёт сам раздел, и от вызова к вызову он не меняется.
    """
    raw = "|".join(str(part) for part in parts)
    return hashlib.sha1(raw.encode("utf-8")).hexdigest()[:VERSION_LENGTH]


def mark_fragment(response: Response, version: str) -> Response:
    """Помечает фрагмент раздела версией и запрещает его кешировать.

    Версия в заголовке говорит клиенту, какую разметку он получил; без
    ``no-store`` браузер мог бы отдать фрагмент из кеша, и версия разошлась бы
    с содержимым.
    """
    response.headers[VERSION_HEADER] = version
    response.headers["Cache-Control"] = "no-store"
    return response
